"""Shared drawing kit for the kids' brand (24 Oct 2026).

Reads characters.json (the kids' choices) and the real die outlines, and gives every page the same pieces:
  python:  shape_svg(), character_svg(), PATTERNS, CHARS   (print files)
  web:     kit.js with the same data and functions        (games, story, site)

python3 kit.py -> kit.js
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "pattern-intro-20261022"))
from build import die  # noqa: E402  real die outline, ears up for 01

NAMES = {"01": ("หมี", "Bear"), "02": ("กังหัน", "Pinwheel"), "03": ("กากบาทแคปซูล", "Capsule cross"),
         "04": ("สี่เหลี่ยมมน", "Rounded square"), "05": ("วงกลม", "Circle"), "07": ("กากบาทข้อต่อวงกลม", "Round-joint cross")}
# where a face sits on each shape (centre x, y in the shape's own mm, and size)
FACE = {"01": (48, 57, 1.0), "02": (45, 45, 1.0), "03": (45, 45, 0.95), "04": (45, 45, 1.0), "05": (45, 45, 1.0), "07": (45, 45, 0.8)}
INK, PAPER, EARTH = "#2A2725", "#F4F0E8", "#A9442B"

PATTERNS = {}
for code in NAMES:
    w, h, cut, sl = die(code)
    PATTERNS[code] = {"w": round(w, 2), "h": round(h, 2), "cut": " ".join(cut.split()), "slit": " ".join(sl.split()),
                      "th": NAMES[code][0], "en": NAMES[code][1], "face": FACE[code]}
CHARS = json.load(open(os.path.join(HERE, "characters.json"), encoding="utf-8"))


def dark(hexcol):
    r, g, b = (int(hexcol[i:i + 2], 16) for i in (1, 3, 5))
    return 0.299 * r + 0.587 * g + 0.114 * b < 110


def shape_svg(code, fill="none", stroke=None, slit=PAPER, sw=0.6):
    """The die outline as SVG markup in its own mm space (0 0 w h)."""
    p = PATTERNS[code]
    line = f' stroke="{stroke}" stroke-width="{sw}"' if stroke else ' stroke="none"'
    return (f'<g fill="{fill}" fill-rule="evenodd"{line} stroke-linejoin="round">{p["cut"]}</g>'
            f'<g fill="none" stroke="{slit}" stroke-width="{max(sw, 0.9)}" stroke-linecap="round">{p["slit"]}</g>')


def face_svg(code, on_dark=False):
    x, y, s = PATTERNS[code]["face"]
    e, hi = (PAPER, INK) if on_dark else (INK, PAPER)
    return (f'<g transform="translate({x} {y}) scale({s}) translate(-45 -45)">'
            f'<circle cx="35" cy="44" r="4.2" fill="{e}"/><circle cx="55" cy="44" r="4.2" fill="{e}"/>'
            f'<circle cx="36.4" cy="42.6" r="1.3" fill="{hi}"/><circle cx="56.4" cy="42.6" r="1.3" fill="{hi}"/>'
            f'<ellipse cx="28" cy="53" rx="4.5" ry="2.6" fill="{EARTH}" opacity=".35"/>'
            f'<ellipse cx="62" cy="53" rx="4.5" ry="2.6" fill="{EARTH}" opacity=".35"/>'
            f'<path d="M39 53 Q45 59 51 53" fill="none" stroke="{e}" stroke-width="2.4" stroke-linecap="round"/></g>')


def character_svg(cid):
    c = next(c for c in CHARS["characters"] if c["id"] == cid)
    return shape_svg(c["pattern"], c["color"], slit="rgba(244,240,232,.45)") + face_svg(c["pattern"], dark(c["color"]))


JS = r"""// Generated by kit.py from characters.json and the real die outlines. Do not edit by hand.
const KIT = (() => {
  const PATTERNS = __PATTERNS__;
  const DATA = __CHARS__;
  const INK = "#2A2725", PAPER = "#F4F0E8", EARTH = "#A9442B";
  const isDark = h => { const n = parseInt(h.slice(1), 16); return (0.299 * (n >> 16) + 0.587 * ((n >> 8) & 255) + 0.114 * (n & 255)) < 110; };
  function shape(code, fill = "none", o = {}) {
    const p = PATTERNS[code], sw = o.sw ?? 0.6;
    const line = o.stroke ? ` stroke="${o.stroke}" stroke-width="${sw}"` : ` stroke="none"`;
    return `<g fill="${fill}" fill-rule="evenodd"${line} stroke-linejoin="round">${p.cut}</g>` +
           `<g fill="none" stroke="${o.slit ?? PAPER}" stroke-width="${Math.max(sw, 0.9)}" stroke-linecap="round">${p.slit}</g>`;
  }
  function face(code, onDark) {
    const [x, y, s] = PATTERNS[code].face, e = onDark ? PAPER : INK, hi = onDark ? INK : PAPER;
    return `<g transform="translate(${x} ${y}) scale(${s}) translate(-45 -45)">` +
      `<circle cx="35" cy="44" r="4.2" fill="${e}"/><circle cx="55" cy="44" r="4.2" fill="${e}"/>` +
      `<circle cx="36.4" cy="42.6" r="1.3" fill="${hi}"/><circle cx="56.4" cy="42.6" r="1.3" fill="${hi}"/>` +
      `<ellipse cx="28" cy="53" rx="4.5" ry="2.6" fill="${EARTH}" opacity=".35"/><ellipse cx="62" cy="53" rx="4.5" ry="2.6" fill="${EARTH}" opacity=".35"/>` +
      `<path d="M39 53 Q45 59 51 53" fill="none" stroke="${e}" stroke-width="2.4" stroke-linecap="round"/></g>`;
  }
  const char = id => DATA.characters.find(c => c.id === id);
  // slits stay visible but quiet on a character, so they read as the real cut, not as marks on the face
  function character(id) { const c = char(id); return shape(c.pattern, c.color, { slit: "rgba(244,240,232,.45)" }) + face(c.pattern, isDark(c.color)); }
  const viewBox = (code, pad = 2) => { const p = PATTERNS[code]; return `${-pad} ${-pad} ${p.w + 2 * pad} ${p.h + 2 * pad}`; };
  return { PATTERNS, DATA, INK, PAPER, shape, face, character, char, viewBox, isDark };
})();
"""

if __name__ == "__main__":
    js = JS.replace("__PATTERNS__", json.dumps(PATTERNS, ensure_ascii=False)).replace("__CHARS__", json.dumps(CHARS, ensure_ascii=False))
    open(os.path.join(HERE, "kit.js"), "w", encoding="utf-8").write(js)
    print("kit.js", len(js), "bytes")
